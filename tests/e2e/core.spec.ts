import { expect, test } from "@playwright/test";
import { e2eEmail, ensureE2EAdmin } from "./support/auth";
import { setPropertyCity } from "./support/property-form";

const adminPassword = process.env.ADMIN_PASSWORD ?? "correct horse battery staple";
const hasDatabase = Boolean(process.env.DATABASE_URL);

test.describe("owners and properties journey", () => {
  test.skip(!hasDatabase, "DATABASE_URL is required for core E2E");
  test.describe.configure({ mode: "serial" });

  test("creates an owner, creates a property, and opens both detail screens", async ({
    page
  }, testInfo) => {
    const suffix = `${testInfo.project.name}-${Date.now()}`.toLowerCase().replace(/[^a-z0-9]+/gu, "-");
    const ownerName = `Owner ${suffix}`;
    const ownerEmail = `owner-${suffix}@example.test`;
    const coOwnerName = `Co Owner ${suffix}`;
    const coOwnerEmail = `co-owner-${suffix}@example.test`;
    const representativeName = `Representative ${suffix}`;
    const propertyName = `Villa ${suffix}`;
    const loginEmail = e2eEmail(`core-${suffix}`, testInfo.project.name);

    await ensureE2EAdmin(loginEmail, adminPassword);

    await page.goto("/en/login");
    await page.getByTestId("login-email").fill(loginEmail);
    await page.getByTestId("login-password").fill(adminPassword);
    await page.getByTestId("login-submit").click();
    await expect(page).toHaveURL(/\/en\/app/u);

    await page.getByRole("link", { name: "Owners" }).click();
    await expect(page.getByTestId("owners-page")).toBeVisible();
    await page.getByTestId("owner-display-name").fill(ownerName);
    await page.getByTestId("owner-email").fill(ownerEmail);
    await page.getByTestId("owner-preferred-locale").selectOption("en");
    await page.getByTestId("owner-representative-display-name").fill(representativeName);
    await page.getByTestId("owner-payout-label").fill("Main MAD bank");
    await page.getByTestId("owner-payout-account-holder").fill(ownerName);
    await page.getByTestId("owner-payout-details").fill("IBAN MA64011519000001205000534921 RIB 1234567890");
    await page.getByTestId("owner-submit").click();

    await expect(page).toHaveURL(/\/en\/app\/owners\/[0-9a-f-]+/u);
    await expect(page.getByTestId("owner-detail-page")).toBeVisible();
    await expect(page.getByRole("heading", { name: ownerName })).toBeVisible();
    await expect(page.getByTestId("owner-detail-email")).toContainText(ownerEmail);
    await expect(page.getByTestId("owner-representatives")).toContainText(representativeName);
    await expect(page.getByTestId("owner-payout-methods")).toContainText("**** 7890");

    await page.goto("/en/app/owners");
    await page.getByTestId("owner-display-name").fill(coOwnerName);
    await page.getByTestId("owner-email").fill(coOwnerEmail);
    await page.getByTestId("owner-preferred-locale").selectOption("en");
    await page.getByTestId("owner-submit").click();
    await expect(page.getByRole("heading", { name: coOwnerName })).toBeVisible();

    await page.goto("/en/app/properties");
    await expect(page.getByTestId("properties-page")).toBeVisible();
    await page.getByTestId("property-owner").selectOption({ label: ownerName });
    await page.getByTestId("property-name").fill(propertyName);
    await page.getByTestId("property-type").fill("Villa");
    await page.getByTestId("property-address").fill("Route de Fes");
    await setPropertyCity(page, "Marrakech");
    await page.getByTestId("property-bedrooms").fill("4");
    await page.getByTestId("property-bathrooms").fill("4");
    await page.getByTestId("property-max-guests").fill("8");
    await page.getByTestId("property-has-pool").check();
    await page.getByTestId("property-operating-pool").check();
    await page.getByTestId("property-operating-pool-frequency").selectOption("DAILY");
    await page.getByTestId("property-operating-midstay").check();
    await page.getByTestId("property-operating-breakfast").check();
    await page.getByTestId("property-operating-chef").check();
    await page.getByTestId("property-operating-transfers").check();
    await page.getByTestId("property-operating-other-services").fill("Hammam, Yoga");
    await page.getByTestId("property-amenities").fill("Pool, Garden, Fiber");
    await page.getByTestId("property-photo-urls").fill("https://assets.example.test/e2e-villa.jpg");
    await page.getByTestId("property-headline").fill("Calm family villa near the Palmeraie");
    await page.getByTestId("property-public-directions").fill("Meet the host at the main gate.");
    await page.getByTestId("property-internal-access-notes").fill("Key safe behind the service entrance.");
    await page.getByTestId("property-house-rules").fill("No parties, Quiet after 22:00");
    await page.getByTestId("property-onboarding-notes").fill("Wi-Fi and linen inventory need final confirmation.");
    await page.getByTestId("property-submit").click();

    await expect(page).toHaveURL(/\/en\/app\/properties\/[0-9a-f-]+/u);
    await expect(page.getByTestId("property-detail-page")).toBeVisible();
    await expect(page.getByRole("heading", { name: propertyName })).toBeVisible();
    await expect(page.getByTestId("property-detail-owner")).toContainText(ownerName);
    await expect(page.getByTestId("property-operating-profile")).toContainText("Pool service");
    await expect(page.getByTestId("property-operating-profile")).toContainText("Daily");
    await expect(page.getByTestId("property-operating-profile")).toContainText("Hammam");
    await expect(page.getByTestId("property-booking-channels-panel")).toBeVisible();
    await page.getByTestId("booking-channel-source-key").fill("AIRBNB");
    await page.getByTestId("booking-channel-display-name").fill("Airbnb Palmeraie");
    await page.getByTestId("booking-channel-external-listing-id").fill(`airbnb-${suffix}`);
    await page.getByTestId("booking-channel-listing-url").fill("https://www.airbnb.com/rooms/123456");
    await page.getByTestId("booking-channel-sync-mode").selectOption("ICAL");
    await page.getByTestId("booking-channel-import-enabled").check();
    await page.getByTestId("booking-channel-sync-endpoint").fill("https://calendar.airbnb.com/ical/private-token.ics");
    await page.getByTestId("booking-channel-submit").click();
    await expect(page.getByTestId("booking-channel-form-success")).toContainText("Booking channel saved");
    await expect(page.getByTestId("booking-channel-summary")).toContainText("Airbnb Palmeraie");
    await expect(page.getByTestId("booking-channel-summary")).toContainText("https://calendar.airbnb.com/***");
    await page.getByTestId("property-operating-groceries").check();
    await page.getByTestId("property-operating-maintenance-frequency").selectOption("MONTHLY");
    await page.getByTestId("property-operating-profile-submit").click();
    await expect(page.getByTestId("property-operating-profile-form-success")).toContainText("Operating profile saved");
    await expect(page.getByTestId("property-operating-profile")).toContainText("Monthly");
    await expect(page.getByTestId("property-operating-profile")).toContainText("Groceries");
    await page.getByTestId("property-owner-share-percent").first().fill("60");
    await page.getByTestId("property-owner-share-add").click();
    await page.getByTestId("property-owner-share-owner").nth(1).selectOption({ label: coOwnerName });
    await page.getByTestId("property-owner-share-percent").nth(1).fill("40");
    await page.getByTestId("property-owner-share-submit").click();
    await expect(page.getByTestId("property-ownership-form-success")).toContainText("Ownership saved");
    await expect(page.getByTestId("property-ownership-summary")).toContainText(ownerName);
    await expect(page.getByTestId("property-ownership-summary")).toContainText(coOwnerName);
    await expect(page.getByTestId("property-ownership-summary")).toContainText("60%");
    await expect(page.getByTestId("property-ownership-summary")).toContainText("40%");
    await page.getByTestId("management-agreement-reference").fill(`MA-${suffix}`);
    await page.getByTestId("management-agreement-reason").fill("Signed owner management agreement");
    await page.getByTestId("management-agreement-effective-from").fill("2026-02-01T09:00");
    await page.getByTestId("management-agreement-commission-rate").fill("1800");
    await page.getByTestId("management-agreement-commission-basis").selectOption("GROSS_ACCOMMODATION");
    await page.getByTestId("management-agreement-accrual-event").selectOption("ON_CHECKOUT");
    await page.getByTestId("management-agreement-expense-treatment").selectOption("DEDUCT_FROM_PAYOUT");
    await page.getByTestId("management-agreement-approval-amount").fill("2500.00");
    await page.getByTestId("management-agreement-approval-key").fill("maintenance");
    await page.getByTestId("management-agreement-approval-requires").selectOption("owner");
    await page.getByTestId("management-agreement-notice-days").fill("60");
    await page.getByTestId("management-agreement-payout-cadence").selectOption("MONTHLY");
    await page.getByTestId("management-agreement-payout-hold-days").fill("7");
    await page.getByTestId("management-agreement-payout-holdback-bps").fill("500");
    await page.getByTestId("management-agreement-owner-responsibilities").fill("Insurance, Major repairs");
    await page.getByTestId("management-agreement-alvillas-responsibilities").fill("Guest operations, Owner reporting");
    await page.getByTestId("management-agreement-special-conditions").fill("Ramadan staffing plan");
    await page.getByTestId("management-agreement-submit").click();
    await expect(page.getByTestId("management-agreement-form-success")).toContainText("Management agreement saved");
    await expect(page.getByTestId("management-agreement-summary")).toContainText(`MA-${suffix}`);
    await expect(page.getByTestId("management-agreement-summary")).toContainText("18%");
    await expect(page.getByTestId("management-agreement-summary")).toContainText("Ramadan staffing plan");
    await expect(page.getByTestId("property-lifecycle-panel")).toBeVisible();
    await expect(page.getByTestId("property-lifecycle-current")).toContainText("Draft");
    await expect(page.getByTestId("property-lifecycle-requirement-ownership")).toContainText("Ready");
    await expect(page.getByTestId("property-lifecycle-requirement-management_agreement")).toContainText("Ready");
    await page.getByTestId("property-lifecycle-status").selectOption("ONBOARDING");
    await page.getByTestId("property-lifecycle-reason").fill("Owner onboarding checklist started");
    await page.getByTestId("property-lifecycle-submit").click();
    await expect(page.getByTestId("property-lifecycle-form-success")).toContainText("Property lifecycle updated");
    await expect(page.getByTestId("property-lifecycle-current")).toContainText("Onboarding");
    await page.getByTestId("property-lifecycle-status").selectOption("ACTIVE");
    await page.getByTestId("property-lifecycle-reason").fill("Activation checklist completed");
    await page.getByTestId("property-lifecycle-submit").click();
    await expect(page.getByTestId("property-lifecycle-form-success")).toContainText("Property lifecycle updated");
    await expect(page.getByTestId("property-lifecycle-current")).toContainText("Active");
    await page.getByTestId("management-agreement-amendment-reason").fill("Signed amendment with owner terms");
    await page.getByTestId("management-agreement-amendment-effective-from").fill("2026-09-01T09:00");
    await page.getByTestId("management-agreement-amendment-commission-rate").fill("2000");
    await page.getByTestId("management-agreement-amendment-commission-basis").selectOption("NET_OF_OTA_FEES");
    await page.getByTestId("management-agreement-amendment-accrual-event").selectOption("ON_RECEIPT");
    await page.getByTestId("management-agreement-amendment-expense-treatment").selectOption("OWNER_PAID");
    await page.getByTestId("management-agreement-amendment-approval-amount").fill("3000.00");
    await page.getByTestId("management-agreement-amendment-notice-days").fill("75");
    await page.getByTestId("management-agreement-amendment-payout-hold-days").fill("10");
    await page.getByTestId("management-agreement-amendment-payout-holdback-bps").fill("250");
    await page.getByTestId("management-agreement-amendment-special-conditions").fill("Summer staffing plan");
    await page.getByTestId("management-agreement-amendment-submit").click();
    await expect(page.getByTestId("management-agreement-amendment-form-success")).toContainText("Agreement amendment saved");
    await expect(page.getByTestId("management-agreement-summary")).toContainText("20%");
    await expect(page.getByTestId("management-agreement-summary")).toContainText("Summer staffing plan");
    await expect(page.getByTestId("management-agreement-history")).toContainText("finance.commission Version 2");
    await page.getByTestId("property-lifecycle-status").selectOption("PAUSED");
    await page.getByTestId("property-lifecycle-reason").fill("Owner requested temporary pause");
    await page.getByTestId("property-lifecycle-submit").click();
    await expect(page.getByTestId("property-lifecycle-current")).toContainText("Paused");
    await page.getByTestId("property-lifecycle-status").selectOption("OFFBOARDED");
    await page.getByTestId("property-lifecycle-reason").fill("Owner completed offboarding");
    await page.getByTestId("property-lifecycle-submit").click();
    await expect(page.getByTestId("property-lifecycle-current")).toContainText("Offboarded");
    await expect(page.getByTestId("property-lifecycle-history")).toContainText("Paused");
    await expect(page.getByTestId("property-lifecycle-history")).toContainText("Offboarded");
    await expect(page.getByTestId("property-lifecycle-no-transitions")).toBeVisible();
    await expect(page.getByTestId("property-onboarding-profile")).toContainText("Calm family villa near the Palmeraie");
    await expect(page.getByTestId("property-onboarding-profile")).toContainText("No parties");
    await expect(page.getByTestId("property-onboarding-profile")).toContainText("1");
  });
});
