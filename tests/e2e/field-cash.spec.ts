import { randomInt } from "node:crypto";
import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { z } from "zod";
import { withTenant } from "@/platform/db/tenant";
import { openFieldFixture } from "./support/field-fixture";
import { storedFieldData } from "./support/field-storage";

test.use({ serviceWorkers: "allow", actionTimeout: 30000, navigationTimeout: 60000 });
for (const locale of ["en", "fr", "ar"] as const) test(`Assigned employee collects cash independently through Phone + PIN in ${locale}`, async ({ page: admin, browser }, info) => {
  test.skip(!process.env.DATABASE_URL, "Real local PostgreSQL is required"); test.setTimeout(360000);
  if (!["localhost", "127.0.0.1"].includes(new URL(process.env.DATABASE_URL!).hostname)) throw new Error("Cash acceptance requires local PostgreSQL");
  const f = await openFieldFixture(admin, info, "en"), origin = new URL(admin.url()).origin;
  const context = await browser.newContext({ baseURL: origin, serviceWorkers: "allow", viewport: { width: info.project.name === "field-mobile" ? 360 : 1440, height: 900 } });
  const otherContext = await browser.newContext({ baseURL: origin, serviceWorkers: "allow", viewport: { width: info.project.name === "field-mobile" ? 360 : 1440, height: 900 } });
  const page = await context.newPage(), phone = `+21266${randomInt(1_000_000, 10_000_000)}`, pin = "368247";
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  try {
    await admin.goto("/en/app/identity"); await admin.getByTestId("invite-display-name").fill(`Dedicated cash driver ${locale}`);
    await admin.getByTestId("invite-phone").fill(phone); await admin.getByTestId("invite-role").selectOption("driver");
    await admin.getByTestId("invite-scope-type").selectOption("job"); await admin.getByTestId("invite-scope-id").fill(f.taskId);
    await admin.getByTestId("invite-preferred-locale").selectOption(locale); await admin.getByTestId("invite-submit").click();
    const code = (await admin.getByTestId("invitation-code").innerText()).split(":").at(-1)?.trim(); expect(code).toBeTruthy();
    await page.goto(`/${locale}/activate/${code}`); await page.getByTestId("activation-phone").fill(phone); await page.getByTestId("activation-pin").fill(pin);
    await page.getByTestId("activation-submit").click(); await expect(page).toHaveURL(new RegExp(`/${locale}/login$`, "u"));
    await page.goto(`/${locale}/login?surface=field`); await page.getByTestId("login-phone").fill(phone); await page.getByTestId("login-pin").fill(pin);
    await page.getByTestId("login-submit").click(); await expect(page).toHaveURL(new RegExp(`/${locale}/app/field$`, "u"));
    const user = z.object({ user: z.object({ id: z.uuid(), personId: z.uuid(), organizationId: z.uuid() }) }).parse(await (await page.request.get("/api/auth/session")).json()).user;
    expect(user.organizationId).toBe(f.organizationId);
    await withTenant(f.db, f.organizationId, async tx => {
      const account = await tx.userAccount.findUniqueOrThrow({ where: { id: user.id }, include: { authCredentials: true } });
      expect(account.passwordHash).toBeNull(); expect(account.authCredentials.find(row => row.type === "PIN")?.secretHash).toMatch(/^\$argon2id\$/u);
      await tx.operationTask.update({ where: { id: f.taskId }, data: { assignedToPersonId: user.personId, assignedToUserAccountId: user.id } });
    });
    await page.goto(`/${locale}/app/field/${f.taskId}`);
    const cash = page.getByTestId("field-cash"); await expect(cash.getByTestId("field-cash-amount")).toBeEnabled();
    const other = await otherContext.newPage();
    await other.goto(`/${locale}/login?surface=field`); await other.getByTestId("login-phone").fill(phone); await other.getByTestId("login-pin").fill(pin);
    await other.getByTestId("login-submit").click(); await expect(other).toHaveURL(new RegExp(`/${locale}/app/field$`, "u"));
    await other.goto(`/${locale}/app/field/${f.taskId}`);
    const otherCash = other.getByTestId("field-cash"); await expect(otherCash.getByTestId("field-cash-amount")).toBeEnabled();
    await otherContext.setOffline(true);
    await otherCash.getByTestId("field-cash-amount").fill("500.25"); await otherCash.getByTestId("field-cash-payer").fill("Dedicated fictional cash guest");
    await otherCash.getByTestId("field-cash-purpose").fill("Dedicated transfer cash acceptance");
    await expect(cash.getByTestId("field-cash-receipt")).toHaveCount(0);
    expect((await page.request.get("/api/field/wallet")).status()).toBe(403);
    await cash.getByTestId("field-cash-amount").fill(locale === "ar" ? "٥٠٠٫٢٥" : "500,25");
    await expect(cash.getByTestId("field-cash-amount")).toHaveValue("500.25");
    await cash.getByTestId("field-cash-payer").fill("Dedicated fictional cash guest");
    await cash.getByTestId("field-cash-purpose").fill("Dedicated transfer cash acceptance");
    await expect.poll(async () => JSON.stringify(await storedFieldData(page, "drafts"))).toContain("500.25");
    await expect.poll(() => page.evaluate(() => navigator.serviceWorker.ready.then(() => Boolean(navigator.serviceWorker.controller)))) .toBe(true);
    await expect.poll(() => page.evaluate(async () => Boolean(await caches.match(`/${document.documentElement.lang}/offline/field`)))).toBe(true);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await context.setOffline(true); await cash.getByTestId("field-cash-save").click(); await expect(cash.getByTestId("field-cash-queued")).toBeVisible();
    const queued = z.array(z.object({ deviceId: z.string(), operation: z.object({ type: z.literal("field_cash.collect"), client_op_id: z.uuid(), client_created_at: z.string(), payload: z.record(z.string(), z.unknown()) }) })).parse(await storedFieldData(page, "operations"));
    expect(queued).toHaveLength(1);
    await page.reload(); await expect(page).toHaveURL(new RegExp(`/${locale}/offline/field\\?task=${f.taskId}$`, "u"));
    await expect(cash.getByTestId("field-cash-amount")).toHaveValue("500.25"); await expect(cash.getByTestId("field-cash-save")).toBeDisabled();
    await expect(cash.getByTestId("field-cash-queued")).toBeVisible();
    expect(await withTenant(f.db, f.organizationId, tx => tx.cashCollection.count({ where: { taskId: f.taskId } }))).toBe(0);
    await context.setOffline(false); await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect.poll(() => withTenant(f.db, f.organizationId, tx => tx.cashCollection.count({ where: { taskId: f.taskId } }))).toBe(1);
    await expect(cash.getByTestId("field-cash-receipt")).toHaveCount(1); await expect(cash.getByTestId("field-cash-amount")).toHaveValue("");
    const replay = await page.request.post("/api/sync/push", { headers: { Origin: origin }, data: { organization_id: f.organizationId, actor_user_id: user.id,
      device_id: queued[0].deviceId, op_schema_version: 1, ops: [queued[0].operation] } });
    expect(replay.status()).toBe(200); expect(await replay.json()).toMatchObject({ results: [{ status: "DUPLICATE" }] });
    await otherCash.getByTestId("field-cash-save").click(); await expect(otherCash.getByTestId("field-cash-queued")).toBeVisible();
    await otherContext.setOffline(false); await other.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(otherCash.getByTestId("field-cash-review-required")).toBeVisible();
    await expect(otherCash.getByTestId("field-cash-confirm-existing")).toBeVisible();
    await otherCash.getByTestId("field-cash-review-reason").fill("Reviewed both dedicated devices: this is the same guest cash");
    await otherCash.getByTestId("field-cash-confirm-existing").click();
    await expect(otherCash.getByTestId("field-cash-review-required")).toHaveCount(0);
    await expect.poll(async () => JSON.stringify(await storedFieldData(other, "operations"))).toContain("resolvedByClientOpId");
    expect((await new AxeBuilder({ page: other }).analyze()).violations).toEqual([]);
    await withTenant(f.db, f.organizationId, async tx => {
      const rows = await tx.cashCollection.findMany({ where: { taskId: f.taskId }, include: { transaction: { include: { postings: true } } } });
      expect(rows).toHaveLength(1); expect(rows[0].collectorUserAccountId).toBe(user.id); expect(rows[0].amount.toFixed(2)).toBe("500.25");
      expect(rows[0].transaction.postings).toHaveLength(2);
      expect(rows[0].transaction.postings.map(row => row.bucket).sort()).toEqual(["CASH_COLLECTION", "UNALLOCATED_COLLECTION"]);
      expect(await tx.outboxEvent.count({ where: { idempotencyKey: `cash:${rows[0].id}:received` } })).toBe(1);
      expect(await tx.auditLog.count({ where: { resourceId: rows[0].id, action: "cash_collection.duplicate_confirmed" } })).toBe(1);
    });
    await expect(page.locator("html")).toHaveAttribute("dir", locale === "ar" ? "rtl" : "ltr");
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await cash.evaluate(element => { (element as HTMLElement).style.fontSize = "200%"; });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    for (const button of await cash.getByRole("button").all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(64);
    await page.screenshot({ path: info.outputPath(`native-field-cash-${locale}.png`), fullPage: true }); expect(errors).toEqual([]);
    await context.setOffline(true);
    for (const checkbox of await page.locator('.field-checklist-items input[type="checkbox"]').all()) await checkbox.check();
    await page.locator('.field-checklist button[type="submit"]').first().click();
    await expect.poll(async () => JSON.stringify(await storedFieldData(page, "operations"))).toContain("field_task.complete");
    await expect(cash.getByTestId("field-cash-amount")).toBeDisabled();
    await page.reload();
    await expect(cash.getByTestId("field-cash-amount")).toBeDisabled();
    await context.setOffline(false); await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(page).toHaveURL(new RegExp(`/${locale}/app/field$`, "u"));
    await withTenant(f.db, f.organizationId, async tx => {
      expect(await tx.auditLog.count({ where: { action: "task.complete", resourceId: f.taskId } })).toBe(1);
      expect(await tx.cashCollection.count({ where: { taskId: f.taskId } })).toBe(1);
    });
  } finally { await Promise.all([context.close(), otherContext.close()]); await f.db.$disconnect(); }
});
