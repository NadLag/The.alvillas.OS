import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { PrismaClient } from "@prisma/client";
import { e2eEmail, ensureE2EAdmin, completeE2EAdminMfa, waitForE2EAdminLoginWindow } from "./support/auth";
import { setPropertyCity } from "./support/property-form";
import { preferOperationPerformer } from "./support/operation-policy";

test.describe("event notification routing", () => {
  test.skip(!process.env.DATABASE_URL, "DATABASE_URL is required for routing E2E");
  test("configures property recipients, routes a real reservation once, and supports persistence, disabled channels, EN FR RTL, keyboard and offline errors", async ({ page }, testInfo) => {
    test.setTimeout(240000);
    const suffix = `${testInfo.project.name}-${Date.now()}`;
    const email = e2eEmail("routing", suffix);
    const password = process.env.ADMIN_PASSWORD ?? "correct horse battery staple";
    await ensureE2EAdmin(email, password);
    await page.goto("/en/login"); await waitForE2EAdminLoginWindow(page, email);
    await page.getByTestId("login-email").fill(email); await page.getByTestId("login-password").fill(password);
    await page.getByTestId("login-submit").click(); await completeE2EAdminMfa(page, email);
    await expect(page).toHaveURL(/\/en\/app$/u);
    const client = new PrismaClient();
    try {
      const account = await client.userAccount.findFirstOrThrow({ where: { email } });
      const ownerName = `Routing owner ${suffix}`;
      const propertyName = `Routing villa ${suffix}`;
      await page.goto("/en/app/owners");
      await page.getByTestId("owner-display-name").fill(ownerName);
      await page.getByTestId("owner-email").fill(`routing-owner-${suffix}@example.test`);
      await page.getByTestId("owner-submit").click(); await expect(page.getByRole("heading", { name: ownerName })).toBeVisible();
      await page.goto("/en/app/properties");
      await page.getByTestId("property-owner").selectOption({ label: ownerName });
      await page.getByTestId("property-name").fill(propertyName); await page.getByTestId("property-type").fill("Villa");
      await page.getByTestId("property-address").fill("Route de Fes");
      const city = await setPropertyCity(page, "Marrakech");
      await page.getByTestId("property-bedrooms").fill("2"); await page.getByTestId("property-bathrooms").fill("2");
      await page.getByTestId("property-max-guests").fill("4"); await page.getByTestId("property-submit").click();
      await expect(page.getByRole("heading", { name: propertyName })).toBeVisible();
      await preferOperationPerformer(email, propertyName);
      const property = await client.property.findFirstOrThrow({ where: { organizationId: account.organizationId, name: propertyName } });
      const adminRole = await client.role.create({ data: { organizationId: account.organizationId, key: `routing-${suffix}`, name: `Routing team ${suffix}` } });
      const permissions = await client.permission.findMany({ where: { organizationId: account.organizationId, key: { in: ["task:view", "reservation:view"] } } });
      expect(permissions).toHaveLength(2);
      await client.rolePermission.createMany({ data: permissions.map((permission) => ({ organizationId: account.organizationId, roleId: adminRole.id, permissionId: permission.id })) });
      await client.roleAssignment.create({ data: { organizationId: account.organizationId, roleId: adminRole.id, userAccountId: account.id, personId: account.personId, scopeType: "property", scopeId: property.id } });
      await page.goto("/en/app/notifications");
      const routing = page.getByTestId("notification-routing");
      await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-event").selectOption("reservation_created");
      await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-scope").selectOption(property.id);
      const role = page.getByTestId(`routing-role-${adminRole.id}`);
      const person = page.getByTestId(`routing-person-${account.personId}`);
      await expect(person).toBeVisible();
      await role.check(); await person.focus(); await page.keyboard.press("Space"); await expect(person).toBeChecked();
      await page.getByTestId("routing-reason").fill("Notify the property team of new reservations");
      await page.getByTestId("routing-save").click(); await expect(page.getByTestId("routing-status")).toContainText("Routing saved");
      await page.reload(); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-event").selectOption("reservation_created"); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-scope").selectOption(property.id); await expect(person).toBeChecked(); await expect(role).toBeChecked();
      await page.goto("/en/app/reservations");
      await page.getByTestId("reservation-property").selectOption({ label: `${propertyName} - ${city}` });
      await page.getByTestId("reservation-guest-name").fill(`Routing guest ${suffix}`);
      await page.getByTestId("reservation-check-in").fill("2027-11-10"); await page.getByTestId("reservation-check-out").fill("2027-11-14");
      await page.getByTestId("reservation-adults").fill("2"); await page.getByTestId("reservation-children").fill("0");
      await page.getByTestId("reservation-submit").click(); await expect(page).toHaveURL(/\/en\/app\/operations/u);
      expect(await page.evaluate((width) => document.documentElement.scrollWidth <= width, page.viewportSize()!.width)).toBe(true);
      await page.getByTestId("notification-bell").click();
      const notice = page.getByTestId("notification-item").filter({ hasText: "A reservation was created." });
      await expect(notice).toHaveCount(1);
      await notice.getByRole("button", { name: "Open record", exact: true }).click();
      await expect(page).toHaveURL(/\/en\/app\/reservations$/u);
      await page.goto("/en/app/notifications"); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-event").selectOption("task_completed"); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-scope").selectOption(property.id); await person.check();
      await page.getByTestId("routing-reason").fill("Notify the assigned team when work is completed");
      await page.getByTestId("routing-save").click(); await expect(page.getByTestId("routing-status")).toContainText("Routing saved");
      await page.goto("/en/app/field");
      await page.getByTestId("field-view-assigned").click();
      await page.getByTestId("field-task-card").filter({ hasText: propertyName }).first().click();
      await expect(page.getByTestId("field-task-page")).toBeVisible();
      const checks = page.getByTestId("field-checklist-item");
      for (let index = 0; index < await checks.count(); index += 1) await checks.nth(index).check();
      await page.getByTestId("field-task-complete").click(); await expect(page).toHaveURL(/\/en\/app\/field$/u);
      await page.getByTestId("notification-bell").click();
      await expect(page.getByTestId("notification-item").filter({ hasText: "A task was completed." })).toHaveCount(1);
      await page.goto("/en/app/notifications"); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-event").selectOption("reservation_created"); await expect(page.getByTestId("routing-in-app")).toBeVisible();
      await page.getByTestId("routing-scope").selectOption(property.id); await expect(person).toBeChecked();
      await page.getByTestId("routing-in-app").uncheck(); await page.getByTestId("routing-reason").fill("Disable optional reservation delivery");
      await page.context().setOffline(true); await expect(page.getByTestId("routing-save")).toBeDisabled();
      await page.context().setOffline(false); await expect(page.getByTestId("routing-save")).toBeEnabled();
      let failNext = true;
      await page.route("**/en/app/notifications", async (route) => {
        if (route.request().method() === "POST" && route.request().postData()?.includes("Disable optional") && failNext) { failNext = false; await route.abort("failed"); } else await route.continue();
      });
      await page.getByTestId("routing-save").click(); await expect(routing.getByRole("alert")).toBeVisible(); await expect(page.getByTestId("routing-in-app")).not.toBeChecked();
      await page.getByTestId("routing-save").click(); await expect(page.getByTestId("routing-status")).toContainText("Routing saved");
      await page.unrouteAll({ behavior: "wait" });
      for (const locale of ["en", "fr", "ar"]) {
        await page.setViewportSize({ width: 360, height: 800 }); await page.goto(`/${locale}/app/notifications`);
        await expect(page.getByTestId("routing-in-app")).toBeVisible();
        await page.getByTestId("routing-event").selectOption("security_session_revoked");
        await expect(page.getByTestId("routing-in-app")).toBeChecked(); await expect(page.getByTestId("routing-in-app")).toBeDisabled();
        await expect(page.getByTestId("routing-email")).toBeChecked(); await expect(page.getByTestId("routing-email")).toBeDisabled();
        await expect(page.getByTestId("routing-push")).not.toBeChecked();
        await expect(page.locator("html")).toHaveAttribute("dir", locale === "ar" ? "rtl" : "ltr");
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
        expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
        await page.screenshot({ path: testInfo.outputPath(`routing-${locale}-360.png`), fullPage: true });
      }
    } finally { await client.$disconnect(); }
  });
});
