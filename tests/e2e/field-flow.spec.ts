import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import en from "../../messages/en.json" with { type: "json" };
import fr from "../../messages/fr.json" with { type: "json" };
import ar from "../../messages/ar.json" with { type: "json" };
import { withTenant } from "@/platform/db/tenant";
import { openFieldFixture } from "./support/field-fixture";
import { storedFieldData } from "./support/field-storage";

test.use({ serviceWorkers: "allow" });
test("Field checklist progress and language preserve unsaved and queued work", async ({ page }, info) => {
  test.skip(!process.env.DATABASE_URL, "Real PostgreSQL is required for field flow acceptance");
  test.setTimeout(240000);
  const fixture = await openFieldFixture(page, info, "en", { checklistItems: 3 });
  const context = page.context(), form = page.getByTestId("field-task-complete-form");
  const counter = page.getByTestId("field-checklist-progress");
  const checks = page.getByTestId("field-checklist-item");
  const finish = page.getByTestId("field-task-complete"), save = form.locator('button[data-progress="true"]');
  const note = form.locator('textarea[name="note"]'), language = page.getByTestId("field-language");
  const label = (locale: "en" | "fr" | "ar", done: number) => ({ en, fr, ar }[locale].Operations.manage.progress.replace("{done}", String(done)).replace("{total}", "3"));
  try {
    await expect(counter).toHaveText(label("en", 0)); await expect(finish).toBeDisabled();
    await expect(form.getByRole("progressbar")).toHaveAttribute("value", "0");
    await checks.nth(0).focus(); await page.keyboard.press("Space");
    await expect(counter).toHaveText(label("en", 1)); await expect(finish).toBeDisabled();
    await note.fill("Keep my unsaved completion note");
    await language.getByTestId("locale-switch-fr").focus(); await page.keyboard.press("Enter");
    await expect(page.getByTestId("field-language-notice")).toHaveText(en.Field.noteBeforeLanguage);
    await expect(page).toHaveURL(new RegExp(`/en/app/field/${fixture.taskId}$`, "u"));
    await expect(note).toHaveValue("Keep my unsaved completion note"); await expect(checks.nth(0)).toBeChecked();
    await note.clear(); await language.getByTestId("locale-switch-fr").click();
    await expect(page.getByTestId("field-language-notice")).toHaveText(en.Field.saveBeforeLanguage);
    await save.click(); await expect(form.getByRole("status")).toHaveText(en.Operations.manage.saved);
    await expect(form).not.toHaveAttribute("data-field-dirty", "true");
    await checks.nth(0).uncheck(); await save.click();
    await expect(form.getByRole("status")).toHaveText(en.Operations.manage.saved);
    await expect(form).not.toHaveAttribute("data-field-dirty", "true");
    await checks.nth(0).check(); await save.click();
    await expect(form.getByRole("status")).toHaveText(en.Operations.manage.saved);
    await expect(form).not.toHaveAttribute("data-field-dirty", "true");
    await language.getByTestId("locale-switch-fr").focus(); await page.keyboard.press("Enter");
    await expect(page).toHaveURL(new RegExp(`/fr/app/field/${fixture.taskId}$`, "u"));
    await expect(counter).toHaveText(label("fr", 1)); await expect(checks.nth(0)).toBeChecked();
    await expect(page.locator("html")).toHaveAttribute("dir", "ltr");
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await checks.nth(1).check(); await expect(counter).toHaveText(label("fr", 2));
    await expect(finish).toBeDisabled(); await save.click();
    await expect(form.getByRole("status")).toHaveText(fr.Operations.manage.saved);
    await expect(form).not.toHaveAttribute("data-field-dirty", "true");
    expect(await withTenant(fixture.db, fixture.organizationId, tx => tx.auditLog.count({ where: { action: "task.checklist.progress", resourceId: fixture.taskId } }))).toBe(4);
    await page.screenshot({ path: info.outputPath("field-progress-fr.png"), fullPage: true });
    await language.getByTestId("locale-switch-ar").click();
    await expect(page).toHaveURL(new RegExp(`/ar/app/field/${fixture.taskId}$`, "u"));
    await expect(page.locator("html")).toHaveAttribute("dir", "rtl");
    await expect(counter).toHaveText(label("ar", 2));
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await context.setOffline(true); await expect(save).toBeDisabled();
    await language.getByTestId("locale-switch-en").click();
    await expect(page.getByTestId("field-language-notice")).toHaveText(ar.Field.offlineLanguage);
    await expect(page).toHaveURL(new RegExp(`/ar/app/field/${fixture.taskId}$`, "u"));
    await expect(checks.nth(0)).toBeChecked(); await expect(checks.nth(1)).toBeChecked();
    await checks.nth(2).focus(); await page.keyboard.press("Space");
    await expect(counter).toHaveText(label("ar", 3)); await expect(finish).toBeEnabled();
    await finish.click(); await expect(page.getByTestId("field-task-sync-status")).toHaveText(ar.Field.offlineQueued);
    const queued = await storedFieldData(page); expect(queued).toHaveLength(1);
    await context.route("**/api/sync/push", route => route.abort()); await context.setOffline(false);
    await expect(page.getByTestId("field-connection")).toContainText(ar.FieldPwa.online);
    await expect(page.getByTestId("field-connection")).not.toContainText(ar.FieldPwa.offline);
    await language.getByTestId("locale-switch-fr").click();
    await expect(page).toHaveURL(new RegExp(`/fr/app/field/${fixture.taskId}$`, "u"));
    await expect(page.getByTestId("field-task-sync-status")).toHaveText(fr.Field.offlineQueued);
    await expect(counter).toHaveText(label("fr", 3)); expect(await storedFieldData(page)).toEqual(queued);
    await expect(page.getByTestId("field-sync-now")).toBeEnabled(); await context.unroute("**/api/sync/push");
    await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(page).toHaveURL(/\/fr\/app\/field$/u); expect(await storedFieldData(page)).toEqual([]);
    expect(await withTenant(fixture.db, fixture.organizationId, tx => tx.auditLog.count({ where: { action: "task.complete", resourceId: fixture.taskId } }))).toBe(1);
    for (const locale of ["en", "ar", "fr"] as const) {
      await language.getByTestId(`locale-switch-${locale}`).click();
      await expect(page).toHaveURL(new RegExp(`/${locale}/app/field$`, "u"));
      await expect(page.locator("html")).toHaveAttribute("dir", locale === "ar" ? "rtl" : "ltr");
      expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    }
  } finally { await fixture.db.$disconnect(); }
});
